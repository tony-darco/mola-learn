/**
 * Reference shapes for the character recognizer (recognize.ts): a few
 * hand-drawn variants of every character it matches by shape, the way
 * different people write them — a "1" bare, flagged, leaning, or with a
 * base, an open and a closed "4", a "7" with and without a crossbar, one- and
 * two-stroke "R"s, a "Z" with a crossbar, a bare, a tailed and a looped "l".
 * ("-" and "=" aren't here: they are recognized from their straight strokes
 * instead; nor is ".", recognized by being a dot.)
 *
 * Each variant is a list of strokes; each stroke is a polyline in pen order,
 * on a grid 10 wide and 16 tall for a capital (x across, y down; lowercase
 * and symbols are drawn at their own proportions). Only the shape matters —
 * the recognizer rescales everything — so the grid is just for drawing.
 *
 * Letters whose capital and lowercase are the same shape at a different size
 * (c C, o O, s S, v V, w W, x X, z Z, u U, p P) share one list: shape can't
 * tell them apart, so the recognizer does it from where the glyph sits on its
 * line (recognize.ts's ZONES). The same goes for ×, which is an x drawn
 * smaller and higher, and ° , a small raised o.
 */
type Stroke = [number, number][];
type Variant = Stroke[];

/** Points round an ellipse, one every `step` degrees. Angles are degrees, y down, so a larger angle turns clockwise on screen. */
function oval(cx: number, cy: number, rx: number, ry: number, from: number, to: number, step = 20): Stroke {
  const n = Math.max(2, Math.round(Math.abs(to - from) / step));
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = ((from + ((to - from) * i) / n) * Math.PI) / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
  });
}

/**
 * The same shapes, squatter. A lowercase letter is about as wide as its
 * capital but little more than half as tall, and the recognizer keeps a
 * glyph's proportions — so a list shared by both cases has both.
 */
const withSquat = (variants: Variant[]): Variant[] => [...variants, ...variants.map((v) => v.map((s) => s.map(([x, y]): [number, number] => [x, 0.6 * y])))];

/** Left–right mirror images, about x = width / 2. */
const mirror = (variants: Variant[], width: number): Variant[] => variants.map((v) => v.map((s) => s.map(([x, y]): [number, number] => [width - x, y])));

